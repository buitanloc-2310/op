c('incident create/update have UI and API', app.includes('incidentStatusModal')&&idx.includes("request.method === 'PATCH'"));
c('user create/edit/lock have UI and API', app.includes('editUserModal')&&idx.includes("status=['active','disabled']"));
c('cannot disable own account', idx.includes('CANNOT_DISABLE_SELF'));
c('last super admin protected', idx.includes('LAST_SUPER_ADMIN'));
c('reports do not hide load failure as empty', app.includes("catch{root.innerHTML=errorBox();return;}"));
