c('querySelectorAll hotfix retained', app.includes("typeof root === 'string' ? document.querySelector(root) : root"));
c('forced password change UI exists', app.includes('renderForcedPassword')&&app.includes('/api/auth/change-password'));
c('password change backend exists', idx.includes("path==='/api/auth/change-password'")&&idx.includes('must_change_password=0'));
c('temporary password flag is enforced', app.includes('state.user.must_change_password'));
