c('no raw frontend error rendering', !/innerHTML[^\n]*(?:err|e)\.message/.test(app));
c('no D1/binding help copy', !app.includes('D1/binding')&&!app.includes('Kiểm tra D1'));
c('no access-scope discussion copy', !app.includes('Nội dung hiển thị theo phạm vi truy cập')&&!app.includes('Nội dung chỉ hiển thị theo quyền'));
